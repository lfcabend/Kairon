package com.kairon.projects.domain;

/**
 * A rough, at-a-glance t-shirt scale of scope (D16) — a plain nullable enum,
 * distinct from {@code estimate_hours} on individual tasks. No default; an
 * unsized project just shows no size badge.
 */
public enum ProjectSize {
    XS,
    S,
    M,
    L,
    XL
}
